//! `generate_figure_eight` — write a figure-eight waypoint script to a `flights/*.csv`.
//!
//! The path is a Gerono lemniscate, by default sized for a consumer-drone ("medium/park")
//! envelope around the start (scripts are relative to where the vehicle starts), with the altitude sweeping smoothly
//! across the loop. It starts and ends over its center, where the lobes cross: centered on the
//! start, the vehicle climbs straight up from it, and `--end land` touches down on it. The
//! header records the command that reproduces the file. Re-run it whenever you want to retune the
//! shape — the flown path lives in the committed CSV, and `ScriptCommander` stays
//! geometry-agnostic. Every dimension is a flag, so you can resize without editing source.
//!
//! It lives in the unpublished `stable-flight-tools` crate so library consumers never compile
//! `clap`.
//!
//! ```bash
//! cargo run --bin generate_figure_eight
//! cargo run --bin generate_figure_eight -- --half-width 40 -o flights/wide.csv
//! cargo run --bin generate_figure_eight -- --center-north 20 --half-width 10
//! ```

use std::error::Error;
use std::f32::consts::PI;
use std::fs;
use std::process;

use clap::Parser;
use clap::builder::RangedU64ValueParser;

#[derive(Parser, Debug)]
#[command(
    about = "Generate a figure-eight (Gerono lemniscate) waypoint script as a flights CSV",
    // Let negative dimensions (e.g. `--alt-mid -5`) parse as values, not flags.
    allow_negative_numbers = true
)]
struct Config {
    /// Output CSV path.
    #[arg(short, long, default_value = "flights/figure_eight.csv")]
    output: String,

    /// Number of legs sampled around the loop; the script has one more waypoint than legs, its
    /// last back at the start.
    #[arg(long, default_value_t = 24, value_parser = RangedU64ValueParser::<usize>::new().range(1..))]
    legs: usize,

    /// Half the figure-eight width, meters (full width is twice this).
    #[arg(long, default_value_t = 30.0)]
    half_width: f32,

    /// Vertical lobe scale, meters.
    #[arg(long, default_value_t = 30.0)]
    height_scale: f32,

    /// Mid altitude of the sweep, meters.
    #[arg(long, default_value_t = 27.5)]
    alt_mid: f32,

    /// Altitude sweep amplitude, meters (altitude spans `alt_mid ± alt_amp`).
    #[arg(long, default_value_t = 12.5)]
    alt_amp: f32,

    /// Constant cruise speed, m/s.
    #[arg(long, default_value_t = 7.0)]
    cruise: f32,

    /// North coordinate of the figure-eight's center, meters (the script's `x`). The default is
    /// the start.
    #[arg(long, default_value_t = 0.0)]
    center_north: f32,

    /// East coordinate of the figure-eight's center, meters (the script's `y`).
    #[arg(long, default_value_t = 0.0)]
    center_east: f32,
}

fn main() {
    let config = Config::parse();
    if let Err(err) = run(&config) {
        eprintln!("error: {err}");
        process::exit(1);
    }
}

/// Builds the CSV and writes it to `config.output`.
fn run(config: &Config) -> Result<(), Box<dyn Error>> {
    fs::write(&config.output, build_csv(config))?;
    println!(
        "wrote {} waypoints ({} legs) to {}",
        config.legs + 1,
        config.legs,
        config.output
    );
    Ok(())
}

/// Renders the figure-eight waypoint script as CSV text (header comment + rows).
///
/// Gerono lemniscate: `x = center_north + half_width*cos(t)`,
/// `y = center_east + height_scale*sin(t)*cos(t)`, `altitude = alt_mid + alt_amp*sin(t)`,
/// sampled at `legs + 1` evenly spaced angles from `t = π/2` to `t = 5π/2`: the first and
/// last rows are the center, at the top of the altitude sweep.
fn build_csv(config: &Config) -> String {
    let mut csv = String::new();
    csv.push_str("# Figure-eight waypoint script, generated by:\n");
    csv.push_str(&format!("# {}\n", command(config)));
    csv.push_str("# Gerono lemniscate: x = center_north + half_width*cos(t),\n");
    csv.push_str(
        "# y = center_east + height_scale*sin(t)*cos(t), altitude = alt_mid + alt_amp*sin(t).\n",
    );
    csv.push_str("# Starts and ends over the center (t = pi/2), where the lobes cross.\n");
    csv.push_str(
        "# Coordinates are m north and east of where the vehicle starts, altitudes m above it.\n",
    );
    csv.push_str("x,y,altitude,cruise_speed\n");

    for i in 0..=config.legs {
        let t = PI / 2.0 + 2.0 * PI * (i as f32) / (config.legs as f32);
        let x = centimeters(config.center_north + config.half_width * t.cos());
        let y = centimeters(config.center_east + config.height_scale * t.sin() * t.cos());
        let altitude = config.alt_mid + config.alt_amp * t.sin();
        csv.push_str(&format!(
            "{x:.2},{y:.2},{altitude:.2},{:.1}\n",
            config.cruise
        ));
    }

    csv
}

/// `value_m` rounded to the centimeter the script writes, without a negative zero (`-0.00`
/// from a cosine a hair below zero at the center).
fn centimeters(value_m: f32) -> f32 {
    // Adding positive zero turns -0.0 into 0.0.
    (value_m * 100.0).round() / 100.0 + 0.0
}

/// The command that writes `config`'s script, every dimension spelled out.
fn command(config: &Config) -> String {
    format!(
        "cargo run --bin generate_figure_eight -- --legs {} --half-width {} --height-scale {} \
         --alt-mid {} --alt-amp {} --cruise {} --center-north {} --center-east {} -o {}",
        config.legs,
        config.half_width,
        config.height_scale,
        config.alt_mid,
        config.alt_amp,
        config.cruise,
        config.center_north,
        config.center_east,
        config.output,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use assert2::check;

    /// Comment lines plus the column header, ahead of the first waypoint row.
    const HEADER_LINES: usize = 7;

    /// The waypoint rows of `csv`, header skipped.
    fn data_rows(csv: &str) -> Vec<&str> {
        csv.lines().skip(HEADER_LINES).collect()
    }

    /// Config with the documented defaults, for tests that tweak one field at a time.
    fn default_config() -> Config {
        Config::parse_from(["generate_figure_eight"])
    }

    #[test]
    fn defaults_match_documented_envelope() {
        let config = default_config();
        check!(config.output == "flights/figure_eight.csv");
        check!(config.legs == 24);
        check!(config.half_width == 30.0);
        check!(config.cruise == 7.0);
        check!(config.center_north == 0.0);
        check!(config.center_east == 0.0);
    }

    #[test]
    fn rejects_zero_legs() {
        check!(Config::try_parse_from(["generate_figure_eight", "--legs", "0"]).is_err());
    }

    #[test]
    fn csv_has_header_and_one_row_per_waypoint() {
        let mut config = default_config();
        config.legs = 4;
        let csv = build_csv(&config);

        check!(csv.lines().nth(HEADER_LINES - 1) == Some("x,y,altitude,cruise_speed"));
        // One row per leg plus the closing row.
        check!(data_rows(&csv).len() == 5);
    }

    /// `--end land` touches down on the last row and the takeoff climbs to the first: both sit
    /// over the center, the start the scripts are centered on (#345).
    #[test]
    fn starts_and_ends_over_the_center() {
        // The eXplora script's dimensions.
        let config = Config::parse_from([
            "generate_figure_eight",
            "--half-width",
            "10",
            "--height-scale",
            "10",
            "--alt-mid",
            "10",
            "--alt-amp",
            "3",
            "--cruise",
            "3",
        ]);
        let csv = build_csv(&config);
        let rows = data_rows(&csv);
        // t = π/2 → the center, at the top of the altitude sweep, without a negative zero.
        check!(rows.first() == Some(&"0.00,0.00,13.00,3.0"));
        check!(rows.last() == Some(&"0.00,0.00,13.00,3.0"));
    }

    #[test]
    fn reaches_both_x_extremes_at_mid_altitude() {
        // 24 legs of π/12 from t = π/2: t = π (row 6) → center_north - half_width,
        // t = 2π (row 18) → center_north + half_width, both at alt_mid.
        let csv = build_csv(&default_config());
        let rows = data_rows(&csv);
        check!(rows[6] == "-30.00,0.00,27.50,7.0");
        check!(rows[18] == "30.00,0.00,27.50,7.0");
    }

    /// The header's command, parsed back, describes the same path.
    #[test]
    fn header_command_reproduces_the_script() {
        let config = Config::parse_from([
            "generate_figure_eight",
            "--half-width",
            "10.5",
            "--center-north",
            "20",
            "--alt-amp",
            "3",
            "-o",
            "flights/small.csv",
        ]);
        let csv = build_csv(&config);
        let header = csv.lines().nth(1).unwrap();
        let args = header
            .strip_prefix("# cargo run --bin generate_figure_eight -- ")
            .unwrap()
            .split_whitespace();
        let reparsed = Config::parse_from(std::iter::once("generate_figure_eight").chain(args));
        check!(build_csv(&reparsed) == csv);
    }

    #[test]
    fn center_offsets_every_waypoint() {
        let config = Config::parse_from([
            "generate_figure_eight",
            "--half-width",
            "10",
            "--center-north",
            "-10.5",
            "--center-east",
            "6.5",
        ]);
        let csv = build_csv(&config);
        // t = π/2 → the center; t = π → (center_north - half_width, center_east).
        let rows = data_rows(&csv);
        check!(rows[0].starts_with("-10.50,6.50,"));
        check!(rows[6].starts_with("-20.50,6.50,"));
    }

    #[test]
    fn dimensions_scale_with_flags() {
        let config =
            Config::parse_from(["generate_figure_eight", "--half-width", "40", "--legs", "8"]);
        let csv = build_csv(&config);
        let rows = data_rows(&csv);
        check!(rows.len() == 9);
        // t = 2π (row 6 of 8 legs from π/2) → center_north + half_width.
        check!(rows[6].starts_with("40.00,"));
    }
}
