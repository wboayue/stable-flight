//! `generate_figure_eight` — write a figure-eight waypoint script to a `flights/*.csv`.
//!
//! The path is a Gerono lemniscate sized for a consumer-drone ("medium/park") envelope, with
//! the altitude sweeping smoothly across the loop. Re-run it whenever you want to retune the
//! shape — the flown path lives in the committed CSV, and `ScriptCommander` stays
//! geometry-agnostic. Every dimension is a flag, so you can resize without editing source.
//!
//! It lives in the unpublished `stable-flight-tools` crate so library consumers never compile
//! `clap`.
//!
//! ```bash
//! cargo run --bin generate_figure_eight
//! cargo run --bin generate_figure_eight -- --half-width 40 -o flights/wide.csv
//! ```

use std::error::Error;
use std::f32::consts::PI;
use std::fs;
use std::process;

use clap::Parser;

#[derive(Parser, Debug)]
#[command(
    about = "Generate a figure-eight (Gerono lemniscate) waypoint script as a flights CSV",
    // Let negative dimensions (e.g. `--alt-mid -5`) parse as values, not flags.
    allow_negative_numbers = true
)]
struct Config {
    /// Output CSV path.
    #[arg(short, long, default_value = "flights/figure_eight.csv")]
    output: String,

    /// Number of waypoints sampled around the loop.
    #[arg(long, default_value_t = 24)]
    waypoints: usize,

    /// Half the figure-eight width, meters (full width is twice this).
    #[arg(long, default_value_t = 30.0)]
    half_width: f32,

    /// Vertical lobe scale, meters.
    #[arg(long, default_value_t = 30.0)]
    height_scale: f32,

    /// Mid altitude of the sweep, meters.
    #[arg(long, default_value_t = 27.5)]
    alt_mid: f32,

    /// Altitude sweep amplitude, meters (altitude spans `alt_mid ± alt_amp`).
    #[arg(long, default_value_t = 12.5)]
    alt_amp: f32,

    /// Constant cruise speed, m/s.
    #[arg(long, default_value_t = 7.0)]
    cruise: f32,
}

fn main() {
    let config = Config::parse();
    if let Err(err) = run(&config) {
        eprintln!("error: {err}");
        process::exit(1);
    }
}

/// Builds the CSV and writes it to `config.output`.
fn run(config: &Config) -> Result<(), Box<dyn Error>> {
    fs::write(&config.output, build_csv(config))?;
    println!("wrote {} waypoints to {}", config.waypoints, config.output);
    Ok(())
}

/// Renders the figure-eight waypoint script as CSV text (header comment + rows).
///
/// Gerono lemniscate: `x = half_width*cos(t)`, `y = height_scale*sin(t)*cos(t)`,
/// `altitude = alt_mid + alt_amp*sin(t)`, sampled at `waypoints` evenly spaced angles.
fn build_csv(config: &Config) -> String {
    let mut csv = String::new();
    csv.push_str("# Figure-eight waypoint script (consumer-drone / medium-park envelope).\n");
    csv.push_str("# Generated by `cargo run --bin generate_figure_eight`.\n");
    csv.push_str("# Gerono lemniscate: x = half_width*cos(t), y = height_scale*sin(t)*cos(t),\n");
    csv.push_str("# altitude = alt_mid + alt_amp*sin(t).\n");
    csv.push_str("x,y,altitude,cruise_speed\n");

    for i in 0..config.waypoints {
        let t = 2.0 * PI * (i as f32) / (config.waypoints as f32);
        let x = config.half_width * t.cos();
        let y = config.height_scale * t.sin() * t.cos();
        let altitude = config.alt_mid + config.alt_amp * t.sin();
        csv.push_str(&format!(
            "{x:.2},{y:.2},{altitude:.2},{:.1}\n",
            config.cruise
        ));
    }

    csv
}

#[cfg(test)]
mod tests {
    use super::*;
    use assert2::check;

    /// Config with the documented defaults, for tests that tweak one field at a time.
    fn default_config() -> Config {
        Config::parse_from(["generate_figure_eight"])
    }

    #[test]
    fn defaults_match_documented_envelope() {
        let config = default_config();
        check!(config.output == "flights/figure_eight.csv");
        check!(config.waypoints == 24);
        check!(config.half_width == 30.0);
        check!(config.cruise == 7.0);
    }

    #[test]
    fn csv_has_header_and_one_row_per_waypoint() {
        let mut config = default_config();
        config.waypoints = 4;
        let csv = build_csv(&config);

        // 4 comment lines + 1 column header + 4 data rows, then a trailing newline.
        let lines: Vec<&str> = csv.lines().collect();
        check!(lines.len() == 9);
        check!(lines[4] == "x,y,altitude,cruise_speed");
    }

    #[test]
    fn first_waypoint_sits_at_the_positive_x_extreme() {
        // t = 0 → x = half_width, y = 0, altitude = alt_mid, cruise constant.
        let config = default_config();
        let csv = build_csv(&config);
        let first_row = csv.lines().nth(5).unwrap();
        check!(first_row == "30.00,0.00,27.50,7.0");
    }

    #[test]
    fn dimensions_scale_with_flags() {
        let config = Config::parse_from([
            "generate_figure_eight",
            "--half-width",
            "40",
            "--waypoints",
            "8",
        ]);
        let csv = build_csv(&config);
        // 4 comment lines + header + 8 rows + trailing newline.
        check!(csv.lines().count() == 13);
        check!(csv.lines().nth(5).unwrap().starts_with("40.00,"));
    }
}
