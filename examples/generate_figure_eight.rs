//! Generates a figure-eight waypoint script and writes it to `flights/figure_eight.csv`.
//!
//! The path is a Gerono lemniscate sized for a consumer-drone ("medium/park") envelope,
//! with the altitude sweeping smoothly across the loop. Re-run this whenever you want to
//! retune the shape — the flown path lives in the committed CSV, and `ScriptCommander`
//! stays geometry-agnostic.
//!
//! ```text
//! cargo run --example generate_figure_eight
//! ```

use std::f32::consts::PI;
use std::fs;

/// Number of waypoints sampled around the figure-eight.
const WAYPOINTS: usize = 24;
/// Half the figure-eight width (meters) -> ~60 m wide.
const HALF_WIDTH: f32 = 30.0;
/// Scales the vertical lobes (meters) -> ~30 m tall (y in [-15, 15]).
const HEIGHT_SCALE: f32 = 30.0;
/// Mid altitude of the sweep (meters).
const ALT_MID: f32 = 27.5;
/// Altitude sweep amplitude (meters) -> altitude in [15, 40].
const ALT_AMP: f32 = 12.5;
/// Constant cruise speed (meters per second).
const CRUISE: f32 = 7.0;

const OUTPUT_PATH: &str = "flights/figure_eight.csv";

fn main() {
    let mut csv = String::new();
    csv.push_str("# Figure-eight waypoint script (consumer-drone / medium-park envelope).\n");
    csv.push_str("# Generated by `cargo run --example generate_figure_eight`.\n");
    csv.push_str("# Gerono lemniscate: x = HALF_WIDTH*cos(t), y = HEIGHT_SCALE*sin(t)*cos(t),\n");
    csv.push_str("# altitude = ALT_MID + ALT_AMP*sin(t); ~60 m wide, ~30 m tall, alt 15-40 m.\n");
    csv.push_str("x,y,altitude,cruise_speed\n");

    for i in 0..WAYPOINTS {
        let t = 2.0 * PI * (i as f32) / (WAYPOINTS as f32);
        let x = HALF_WIDTH * t.cos();
        let y = HEIGHT_SCALE * t.sin() * t.cos();
        let altitude = ALT_MID + ALT_AMP * t.sin();
        csv.push_str(&format!("{x:.2},{y:.2},{altitude:.2},{CRUISE:.1}\n"));
    }

    fs::write(OUTPUT_PATH, csv).expect("failed to write figure_eight.csv");
    println!("wrote {WAYPOINTS} waypoints to {OUTPUT_PATH}");
}
